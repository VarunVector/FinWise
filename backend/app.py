"""
Flask API server for LSTM Stock Predictions.
Serves the predictions generated by generate_predictions.py
from data/predictions.json at GET /api/stocks/predictions
"""
import os
import json
from flask import Flask, jsonify
from flask_cors import CORS

app = Flask(__name__)
CORS(app)  # Enable CORS for frontend access

# Path to the predictions file
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
PREDICTIONS_PATH = os.path.join(BASE_DIR, 'data', 'predictions.json')


@app.route('/api/stocks/predictions', methods=['GET'])
def get_predictions():
    if not os.path.exists(PREDICTIONS_PATH):
        return jsonify({
            'success': False,
            'message': 'predictions.json not found. Please run generate_predictions.py first.'
        }), 404

    try:
        with open(PREDICTIONS_PATH, 'r', encoding='utf-8') as f:
            predictions = json.load(f)

        return jsonify({
            'success': True,
            'data': predictions
        })
    except Exception as e:
        return jsonify({
            'success': False,
            'message': f'Failed to read predictions: {str(e)}'
        }), 500


@app.route('/api/health', methods=['GET'])
def health():
    return jsonify({'success': True, 'status': 'ok'})


if __name__ == '__main__':
    app.run(host='0.0.0.0', port=5000, debug=True)

